// Builds the generated design files from design/tokens.json and checks contrast.
//
//   node design/scripts/build-tokens.mjs          write tokens.css, model-shapes.json
//                                                 and the contrast tables in identity.md
//   node design/scripts/build-tokens.mjs --check  write nothing; exit 1 if a generated
//                                                 file is out of date or a colour is
//                                                 below 4.5:1 on a ground colour
//
// No dependencies. Node 20 or later.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const designDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const file = (name) => join(designDir, name);
const check = process.argv.includes("--check");

const tokens = JSON.parse(readFileSync(file("tokens.json"), "utf8"));
const { color } = tokens;

// ---------- tokens.css ----------

const fontStack = (list) => list.map((f) => (/^[a-z-]+$/.test(f) ? f : `"${f}"`)).join(", ");

function buildCss() {
  const out = [
    "/* Orbitrace design tokens. Generated from design/tokens.json by design/scripts/build-tokens.mjs. Do not edit by hand. */",
    ":root {",
    "  color-scheme: dark;",
  ];
  for (const [group, values] of Object.entries(color)) {
    out.push(`  /* ${group} */`);
    for (const [name, value] of Object.entries(values)) out.push(`  --${name}: ${value};`);
  }
  out.push("  /* font */");
  for (const [role, list] of Object.entries(tokens.font))
    out.push(`  --font-${role}: ${fontStack(list)};`);
  out.push("  /* space */");
  for (const [step, value] of Object.entries(tokens.space))
    out.push(`  --space-${step}: ${value};`);
  out.push("  /* radius */");
  for (const [name, value] of Object.entries(tokens.radius))
    out.push(`  --radius-${name}: ${value};`);
  out.push("}", "");
  return out.join("\n");
}

// ---------- model-shapes.json ----------
// Same geometry as the concept prototype's shapePts(), evaluated at radius 1.

const round4 = (n) => Math.round(n * 1e4) / 1e4 + 0; // + 0 turns -0 into 0
function ring(count, radiusAt, dy = 0) {
  return Array.from({ length: count }, (_, i) => {
    const a = -Math.PI / 2 + (i * 2 * Math.PI) / count;
    const r = radiusAt(i);
    return [round4(Math.cos(a) * r), round4(Math.sin(a) * r + dy)];
  });
}

function buildShapes() {
  const shapes = {
    $comment:
      "Agent node shapes. Points are for a node of radius 1 centred on (0, 0), y pointing down, first point at the top, clockwise. Multiply by the node radius. Generated by design/scripts/build-tokens.mjs. Do not edit by hand.",
    families: {
      fable: {
        label: "Fable",
        shape: "eight-point burst",
        points: ring(16, (i) => (i % 2 ? 0.86 : 1.22)),
        core: [0, 0],
      },
      opus: { label: "Opus", shape: "hexagon", points: ring(6, () => 1.1), core: [0, 0] },
      sonnet: { label: "Sonnet", shape: "diamond", points: ring(4, () => 1.18), core: [0, 0] },
      haiku: {
        label: "Haiku",
        shape: "triangle",
        points: ring(3, () => 1.3, 0.18),
        core: [0, 0.18],
      },
      unknown: { label: "Unknown", shape: "circle", points: null, radius: 1, core: [0, 0] },
    },
    inner: {
      $comment:
        "The effort fill is the outer shape scaled about (0, 0) by scaleBase + scaleSpan * fill. Nothing is drawn when fill is 0.",
      scaleBase: 0.25,
      scaleSpan: 0.6,
    },
    effort: {
      low: { fill: 0, look: "hollow" },
      medium: { fill: 0.4 },
      high: { fill: 0.6 },
      xhigh: { fill: 0.8 },
      max: { fill: 1, look: "solid with a white core" },
    },
    unknownEffortFill: 0.25,
    whiteCore: {
      $comment: "Drawn at max effort only, at the family's core point.",
      color: "#FFFFFF",
      radius: round4(2.2 / 15),
    },
  };
  // Keep each [x, y] pair on one line.
  return (
    JSON.stringify(shapes, null, 2).replace(/\[\s+(-?[\d.]+),\s+(-?[\d.]+)\s+\]/g, "[$1, $2]") +
    "\n"
  );
}

// ---------- contrast (WCAG 2.2 relative luminance and contrast ratio) ----------

const channel = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => channel(parseInt(hex.slice(i, i + 2), 16) / 255));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

const AA = 4.5;
const grounds = Object.entries(color.ground);
const textColours = Object.entries(color.text);
const otherColours = [color.brand, color.dimension, color.status].flatMap(Object.entries);
const failures = [];

function table(rows) {
  const lines = [
    `| token | ${grounds.map(([g, v]) => `${g} \`${v}\``).join(" | ")} |`,
    `|---|${grounds.map(() => "---:").join("|")}|`,
  ];
  for (const [name, value] of rows) {
    const cells = grounds.map(([g, bg]) => {
      const r = contrast(value, bg);
      if (r < AA) {
        failures.push(`${name} on ${g}: ${r.toFixed(2)}`);
        return `${r.toFixed(2)} (below AA)`;
      }
      return r.toFixed(2);
    });
    lines.push(`| \`--${name}\` \`${value}\` | ${cells.join(" | ")} |`);
  }
  return lines.join("\n");
}

const contrastBlock = [
  "<!-- contrast:start (generated by design/scripts/build-tokens.mjs, do not edit by hand) -->",
  "Text colours:",
  "",
  table(textColours),
  "",
  "Brand, dimension and status colours, for labels, headings and links set in these colours:",
  "",
  table(otherColours),
  "<!-- contrast:end -->",
].join("\n");

// ---------- write or check ----------

const identityPath = file("identity.md");
const identity = readFileSync(identityPath, "utf8");
const blockRe = /<!-- contrast:start[\s\S]*?<!-- contrast:end -->/;
if (!blockRe.test(identity)) {
  console.error("identity.md has no contrast:start / contrast:end markers");
  process.exit(1);
}

const outputs = [
  [file("tokens.css"), buildCss()],
  [file("model-shapes.json"), buildShapes()],
  [identityPath, identity.replace(blockRe, contrastBlock)],
];

let stale = 0;
for (const [path, content] of outputs) {
  let current = null;
  try {
    current = readFileSync(path, "utf8");
  } catch {
    /* file not written yet */
  }
  const name = path.slice(designDir.length + 1);
  if (current === content) {
    console.log(`up to date  design/${name}`);
  } else if (check) {
    console.log(`OUT OF DATE design/${name}`);
    stale++;
  } else {
    writeFileSync(path, content);
    console.log(`wrote       design/${name}`);
  }
}

console.log(`\n${contrastBlock}\n`);
console.log(
  `white core on --wire (non-text marker): ${contrast("#FFFFFF", color.dimension.wire).toFixed(2)}`,
);

if (failures.length) console.log(`\nBelow ${AA}:1:\n  ${failures.join("\n  ")}`);
else
  console.log(
    `\nAll ${(textColours.length + otherColours.length) * grounds.length} pairs are at or above ${AA}:1.`,
  );

process.exit(failures.length || stale ? 1 : 0);
